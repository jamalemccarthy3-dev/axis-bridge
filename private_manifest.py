"""private_manifest.py - writes PRIVATE_MODULES.md: the NAMES of the private bridge and utility files, never their code.

The code of these files stays on this machine (they match the 'private code' patterns in .gitignore and are not tracked). The public repo
shows only this list, so a reader sees which utilities exist in each engine. Run after adding or renaming such files:
    python private_manifest.py
"""
import fnmatch
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PATTERNS = ["bridge_*.py", "*_bridge.py", "*_bridge_*.py", "*_tool.py", "*_utility*.py", "*utility_tool*.py"]
SKIP = {"__pycache__", ".git", "node_modules", "bridge_env", "instantmesh_env", "InstantMesh", "nvdiffrast", "dist", "build"}


def tracked():
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
    return {p for p in out if p}


def is_private(rel):
    parts = rel.split("/")
    return "lib" in parts[:-1] or any(fnmatch.fnmatch(parts[-1], p) for p in PATTERNS)


def main():
    t = tracked()
    found = []
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = [d for d in dn if d not in SKIP and not os.path.exists(os.path.join(dp, d, ".git"))]   # nested repos publish (or not) on their own
        for f in fn:
            rel = os.path.relpath(os.path.join(dp, f), ROOT).replace(os.sep, "/")
            if rel not in t and is_private(rel) and f != "__init__.py" and not f.endswith((".pyc", ".log")):
                found.append(rel)
    found.sort()
    groups = {}
    for rel in found:
        folder, name = rel.rsplit("/", 1) if "/" in rel else (".", rel)
        groups.setdefault(folder, []).append(name)
    lines = ["# Private modules (names only)", "",
             "These files exist in the working copy but their code is not published. This list is generated by `private_manifest.py`; it shows what the",
             "engines contain, not how they work.", "", "%d files in %d folders." % (len(found), len(groups)), ""]
    for folder in sorted(groups):
        lines += ["## " + folder, ""] + ["- " + n for n in groups[folder]] + [""]
    with open(os.path.join(ROOT, "PRIVATE_MODULES.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote PRIVATE_MODULES.md: %d files in %d folders" % (len(found), len(groups)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
