"""Module gateway: one front door (one port) for every independent module in the UI folder, discovered automatically.

DROP IN / TAKE OUT. A module is just a folder in axis-ui-interface/ with a small module.json (its name, hostname, port,
how to start it). The gateway notices it within seconds: it starts the module, routes http://<its hostname>:8080/ to it,
and (if the module declares a NEXXUS window) publishes it to NEXXUS. Remove the folder, or its <name>.module.json
pointer file, and it disappears from routing and from NEXXUS the same way; the gateway stops a module it started.
Anything that is not a module (project-X, config, lib, silos...) has no module.json and is ignored.

Routing is by HOSTNAME, every module is its own process on its own 127.0.0.1 port, and each hostname is a separate
browser origin, so a crash, a bug or a leaked session in one cannot touch another. The gateway is deliberately NOT
part of NEXXUS or the bridge: it never forwards to the bridge port (8000), never starts the bridge, only ever stops
a process it started itself, and one bad manifest is reported and skipped without affecting the others.

    python gateway.py            # launcher page at http://localhost:8080/
    python gateway.py --check    # discover + validate and exit
"""
