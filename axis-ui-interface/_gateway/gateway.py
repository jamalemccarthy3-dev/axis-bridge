_ID_LIKE = re.compile(r"[0-9a-fA-F]{24,}|[A-Za-z0-9_\-]{40,}")


def is_outside(headers, client_ip):
    """True if this request arrived through a tunnel / proxy or from another machine. Used to keep NEXXUS local-only."""
    return any(headers.get(h) for h in OUTSIDE_HINTS) or client_ip not in ("127.0.0.1", "::1")


def clean_path(raw):
    """A path safe to write in the log: query VALUES are dropped (only the parameter names are kept) and anything that looks
    like a token / long id becomes [id]."""
    p = urllib.parse.urlparse(str(raw or ""))
    q = "?" + "&".join(sorted({k for k, _ in urllib.parse.parse_qsl(p.query, keep_blank_values=True)}))[:120] if p.query else ""
    return _ID_LIKE.sub("[id]", p.path[:200]) + q


class BusLog:
    """The gateway's private traffic record: one JSON line per request or lifecycle event. It records WHO talked to WHOM and how it went -
    never request or response contents, headers, cookies or query values. With no path it does nothing (tests, --check)."""
    ROTATE = 5_000_000

    def __init__(self, path=None):
        self.path, self.lock = path, threading.Lock()

    def _write(self, entry):
        if not self.path:
            return
        entry = dict(entry, ts=round(time.time(), 2), when=time.strftime("%Y-%m-%d %H:%M:%S"))
        with self.lock:
            try:
                os.makedirs(os.path.dirname(self.path), exist_ok=True)
                if os.path.exists(self.path) and os.path.getsize(self.path) > self.ROTATE:
                    for i in (2, 1):
                        if os.path.exists(f"{self.path}.{i}"):
                            os.replace(f"{self.path}.{i}", f"{self.path}.{i + 1}")
                    os.replace(self.path, self.path + ".1")
                with open(self.path, "a", encoding="utf-8") as f:
                    f.write(json.dumps(entry, ensure_ascii=False) + "\n")
            except OSError:
                pass                                          # a log problem must never break routing

    def request(self, module, host, method, path, status, bytes_in, bytes_out, ms, outside):
        self._write({"kind": "request", "module": module, "host": re.sub(r"[^a-z0-9.:\[\]-]", "", str(host).lower())[:80], "method": method,
                     "path": clean_path(path), "status": status, "in": bytes_in, "out": bytes_out, "ms": ms, "outside": bool(outside)})

    def event(self, what, **fields):
        self._write(dict({"kind": "event", "what": what}, **{k: str(v)[:200] for k, v in fields.items()}))


def _port_free(port):
    import socket
    s = socket.socket()
    try:
        s.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False
    finally:
        s.close()


class AutoPorts:
    """Hands out free loopback ports to modules that declare "port": "auto", and remembers them so a module keeps the same port
    across restarts (tunnels, bookmarks and the NEXXUS roster stay valid). Never touches a module with a fixed port."""

    def __init__(self, path):
        self.path = path
        try:
            self.data = json.load(open(path, encoding="utf-8")) if path and os.path.exists(path) else {}
        except (OSError, ValueError):
            self.data = {}

    def assign(self, name, key, used, probe):
        """-> a port number, or None if the range is full. used = ports already claimed; probe(port) = is this module answering there."""
        saved = (self.data.get(name) or {}).get(key)
        if isinstance(saved, int) and saved not in used and (probe(saved) or _port_free(saved)):
            return saved
        lo, hi = AUTO_RANGE
        import zlib
        start = zlib.crc32(name.encode()) % (hi - lo + 1)
        for i in range(hi - lo + 1):
            cand = lo + (start + i) % (hi - lo + 1)
            if cand not in used and _port_free(cand):
                self.data.setdefault(name, {})[key] = cand
                self._save()
                return cand
        return None

    def _save(self):
        if not self.path:
            return
        try:
            tmp = self.path + ".tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                json.dump(self.data, f, indent=1)
            os.replace(tmp, self.path)
        except OSError:
            pass


def _http_ok(port, path):
    try:
        c = http.client.HTTPConnection("127.0.0.1", port, timeout=1.0)
        c.request("GET", path)
        ok = c.getresponse().status == 200
        c.close()
        return ok
    except (OSError, http.client.HTTPException):
        return False


def _resolve_auto_ports(name, mod, cfg, auto, fixed=()):
    """Fill in "auto" ports. `fixed` = every fixed port any module declares. Returns a plain-words problem, or ''."""
    keys = [k for k in ("port", "webhook_port") if mod.get(k) == "auto"]
    if not keys:
        return ""
    if auto is None:
        return 'port "auto" needs the gateway\'s port store'
    gw = (cfg.get("gateway") or {}).get("port")
    used = {p for p in [gw] + list((cfg.get("reserved") or {}).values()) if isinstance(p, int)} | set(fixed)
    for m in cfg["modules"].values():
        used |= {m[k] for k in ("port", "webhook_port") if isinstance(m.get(k), int)}
    used |= {mod[k] for k in ("port", "webhook_port") if isinstance(mod.get(k), int)}
    for k in keys:
        p = auto.assign(name, k, used, lambda port: _http_ok(port, mod.get("health", "/api/health")))
        if p is None:
            return f"no free port left in {AUTO_RANGE[0]}-{AUTO_RANGE[1]} for {k}"
        mod[k] = p
        used.add(p)
    return ""


def _fill(text, m):
    """Replace {port} / {webhook_port} in a start command or env value."""
    return str(text).replace("{port}", str(m.get("port", ""))).replace("{webhook_port}", str(m.get("webhook_port", "")))


def load_config(path=CONFIG_PATH):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _read_json(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else None
    except (OSError, ValueError):
        return None


def resolve_cwd(spec):
    """First existing folder from a path or a list of candidate paths (relative ones are relative to the UI folder)."""
    for c in spec if isinstance(spec, list) else [spec]:
        p = c if os.path.isabs(c) else os.path.normpath(os.path.join(UI_DIR, c))
        if os.path.isdir(p):
            return p
    return None


def _inside(path, root):
    path, root = os.path.realpath(path), os.path.realpath(root)
    return path == root or path.startswith(root + os.sep)


# ---------------------------------------------------------------------- discovery
def find_modules(ui_dir):
    """Return [(manifest_path, folder, source, via)] for every module folder or pointer file in the UI folder."""
    out = []
    for name in sorted(os.listdir(ui_dir)):
        full = os.path.join(ui_dir, name)
        if name.startswith(("_", ".")):
            continue
        if os.path.isdir(full) and os.path.isfile(os.path.join(full, "module.json")):
            out.append((os.path.join(full, "module.json"), full, full, "folder"))
        elif os.path.isfile(full) and name.endswith(".module.json"):
            ptr = _read_json(full) or {}
            folder = ptr.get("folder")
            if folder:
                folder = folder if os.path.isabs(folder) else os.path.normpath(os.path.join(ui_dir, folder))
                out.append((os.path.join(folder, "module.json"), folder, full, "pointer"))
            else:
                out.append((None, None, full, "pointer"))
    return out


def build_module(manifest, folder):
    """Turn a module.json into a gateway module entry, or raise ValueError with a plain reason."""
    name = str(manifest.get("name", ""))
    if not NAME_RE.match(name):
        raise ValueError("name must be lowercase letters, numbers, - or _")
    kind = manifest.get("type", "app")
    mod = {"type": kind, "hostnames": [str(h).lower() for h in manifest.get("hostnames", [])], "note": str(manifest.get("note", ""))[:300], "_folder": folder}
    if not mod["hostnames"] or not all(HOST_RE.match(h) for h in mod["hostnames"]):
        raise ValueError("hostnames must be plain host names such as blog.localhost")
    if kind == "static":
        root = os.path.normpath(os.path.join(folder, manifest.get("root", ".")))
        if not _inside(root, folder):
            raise ValueError("static root must be inside the module folder")
        mod.update(root=root, index=manifest.get("index", "index.html"), files=list(manifest.get("files", [])), prefixes=list(manifest.get("prefixes", [])))
        return name, mod
    if kind != "app":
        raise ValueError(f"unknown type {kind!r}")
    mod["port"] = manifest.get("port")
    for key in ("webhook_port", "webhook_paths", "health", "private_paths", "wake_timeout", "idle_minutes", "keep_running", "proxy_timeout"):
        if key in manifest:
            mod[key] = manifest[key]
    start = manifest.get("start")
    if start:
        cmd = start.get("cmd")
        if not isinstance(cmd, list) or not cmd or str(cmd[0]) not in ALLOWED_RUNNERS:
            raise ValueError("start.cmd must be a list beginning with {python} or node")
        sub = os.path.normpath(os.path.join(folder, start.get("cwd", ".")))
        if not _inside(sub, folder):
            raise ValueError("start.cwd must be inside the module folder")
        mod["start"] = {"cwd": sub, "cmd": [str(c) for c in cmd], "env": {str(k): str(v) for k, v in (start.get("env") or {}).items()}}
    nx = manifest.get("nexxus")
    if nx:
        nx = nx if isinstance(nx, dict) else {}
        secret = os.path.normpath(os.path.join(folder, nx.get("secret_file", "nexxus.secret")))
        if not _inside(secret, folder):
            raise ValueError("nexxus.secret_file must be inside the module folder")
        mod["_nexxus"] = {"path": nx.get("path", "/api/nexxus/rpc"), "secret_file": secret}
    return name, mod


def _proxy_timeout(module):
    """Seconds the gateway waits for a module's reply: 60 by default, up to an hour for modules that run long jobs."""
    try:
        return min(max(float(module.get("proxy_timeout", 60)), 5.0), 3600.0)
    except (TypeError, ValueError):
        return 60.0


def validate(cfg):
    """Return a list of problems. An empty list means the routing table is safe to run."""
    errors, used_ports, used_hosts = [], {}, {}
    reserved = {int(p): name for name, p in cfg.get("reserved", {}).items()}
    gw = cfg.get("gateway", {})
    if gw.get("port") in reserved:
        errors.append(f"gateway port {gw['port']} is reserved for {reserved[gw['port']]}")
    used_ports[gw.get("port")] = "gateway"
    b = cfg.get("bridge")
    if b:
        for h in b.get("hostnames", []):
            if not HOST_RE.match(str(h)):
                errors.append(f"bridge: hostname {h!r} is not a plain host name")
            if h in used_hosts or h in LAUNCHER_HOSTS:
                errors.append(f"bridge: hostname {h} clashes with another route")
            used_hosts[h] = "bridge"
        if not b.get("hostnames"):
            errors.append("bridge: needs at least one hostname")
        if not isinstance(b.get("port"), int) or b.get("port") not in reserved:
            errors.append("bridge: port must be the reserved nexxus_bridge port")
        if b.get("local_only") is not True:
            errors.append("bridge: the NEXXUS route must stay local_only (it is never allowed to be reachable through a tunnel or proxy)")
    for name, m in cfg.get("modules", {}).items():
        kind = m.get("type", "app")
        if kind not in ("app", "static"):
            errors.append(f"{name}: unknown type {kind!r}")
        if not m.get("hostnames"):
            errors.append(f"{name}: needs at least one hostname")
        for h in m.get("hostnames", []):
            if h in used_hosts:
                errors.append(f"hostname {h} is used by both {used_hosts[h]} and {name}")
            if h in LAUNCHER_HOSTS:
                errors.append(f"{name}: hostname {h} is reserved for the launcher page")
            used_hosts[h] = name
        if kind == "app":
            for key in ("port", "webhook_port"):
                p = m.get(key)
                if p is None:
                    if key == "port":
                        errors.append(f"{name}: needs a port")
                    continue
                if not isinstance(p, int) or not 1024 <= p <= 65535:
                    errors.append(f"{name}: {key} must be a number between 1024 and 65535")
                    continue
                if p in reserved:
                    errors.append(f"{name}: {key} {p} is reserved for {reserved[p]} (modules must never route to it)")
                if p in used_ports:
                    errors.append(f"{name}: {key} {p} is already used by {used_ports[p]}")
                used_ports[p] = f"{name}.{key}"
            st = m.get("start")
            if st is not None and (not isinstance(st.get("cmd"), list) or not st.get("cwd")):
                errors.append(f"{name}: start needs a cmd list and a cwd")
            if m.get("keep_running") and not st:
                errors.append(f"{name}: keep_running needs a start command (the gateway cannot launch it otherwise)")
            if m.get("idle_minutes") and not st:
                errors.append(f"{name}: idle_minutes needs a start command (the gateway can only rest what it started)")
            if not str(m.get("health", "/")).startswith("/"):
                errors.append(f"{name}: health must be a path starting with /")
        else:
            root = m.get("root")
            if not root or not os.path.isdir(os.path.join(HERE, root) if not os.path.isabs(root) else root):
                errors.append(f"{name}: static root folder not found: {root}")
    return errors


def discover(base_cfg, ui_dir, auto=None):
    """Merge ports.json with every module found in the UI folder. Returns (cfg, problems). A bad manifest is skipped, never fatal."""
    cfg = dict(base_cfg, modules=dict(base_cfg.get("modules", {})))
    problems, seen = [], set(cfg["modules"])
    found = find_modules(ui_dir)
    found.sort(key=lambda t: 0 if t[3] == "folder" else 1)          # a real folder in the UI root beats a leftover pointer file
    # Every fixed port any module declares is off limits to automatic ones, whichever module is found first.
    fixed = set()
    for manifest_path, _folder, _source, _via in found:
        m = _read_json(manifest_path) if manifest_path else None
        for key in ("port", "webhook_port"):
            if m and isinstance(m.get(key), int) and not isinstance(m.get(key), bool):
                fixed.add(m[key])
    for manifest_path, folder, source, via in found:
        label = os.path.basename(source)
        if manifest_path is None:
            problems.append(f"{label}: pointer file needs a \"folder\" entry")
            continue
        manifest = _read_json(manifest_path)
        if manifest is None:
            problems.append(f"{label}: cannot read {manifest_path} (missing folder or invalid JSON)")
            continue
        try:
            name, mod = build_module(manifest, folder)
        except (ValueError, TypeError, AttributeError) as exc:
            problems.append(f"{label}: {exc}")
            continue
        if name in seen:
            problems.append(f"{label}: a module called {name!r} is already registered; this one is ignored")
            continue
        auto_problem = _resolve_auto_ports(name, mod, cfg, auto, fixed)
        if auto_problem:
            problems.append(f"{label}: {auto_problem}")
            continue
        errs = [e for e in validate(dict(cfg, modules={**cfg["modules"], name: mod})) if name in e]
        if errs:
            problems.append(f"{label}: " + "; ".join(errs))
            continue
        cfg["modules"][name] = mod
        seen.add(name)
    return cfg, problems


def publish_for_nexxus(cfg, path, gw_port):
    """Write the roster NEXXUS reads (nexxus_external.py). Returns problems; rewrites the file only when it changed."""
    problems, out = [], {"_generated_by": GENERATED_NOTE}
    for name, m in cfg["modules"].items():
        nx = m.get("_nexxus")
        if not nx:
            continue
        try:
            ok = len(open(nx["secret_file"], encoding="utf-8").read().strip()) >= 32
        except OSError:
            ok = False
        if not ok:
            problems.append(f"{name}: has a NEXXUS window but no usable secret file ({os.path.basename(nx['secret_file'])}); not published to NEXXUS")
            continue
        out[name] = {"base": f"http://127.0.0.1:{gw_port}", "host": f"{m['hostnames'][0]}:{gw_port}", "path": nx["path"], "secret_file": nx["secret_file"]}
    text = json.dumps(out, indent=2) + "\n"
    try:
        if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
            tmp = path + ".tmp"
            open(tmp, "w", encoding="utf-8").write(text)
            os.replace(tmp, path)
    except OSError as exc:
        problems.append(f"could not write the NEXXUS roster: {exc}")
    return problems


# ---------------------------------------------------------------------- waking and keeping modules running
class Supervisor:
    """Starts modules, keeps keep_running ones alive, optionally rests idle ones. It only ever stops processes it started."""

    def __init__(self, cfg, clock=time.time):
        self.cfg, self.clock = cfg, clock
        self.mods, self.state = {}, {}
        self.on_event = None                    # optional callback(what, **fields): the bus log hooks in here
        self.update(cfg)

    def update(self, cfg):
        """Adopt a new routing table: keep state for modules that remain, rest the ones that were removed."""
        self.cfg = cfg
        new = {n: m for n, m in cfg["modules"].items() if m.get("type", "app") == "app" and m.get("start")}
        for n in list(self.state):
            if n not in new:
                self.stop(n)                       # its folder or manifest was removed: stop what we started
                del self.state[n]
        for n in new:
            self.state.setdefault(n, {"proc": None, "lock": threading.Lock(), "last": 0.0, "inflight": 0, "owned": False, "error": ""})
        self.mods = new

    def healthy(self, module):
        try:
            c = http.client.HTTPConnection("127.0.0.1", module["port"], timeout=1.5)
            c.request("GET", module.get("health", "/api/health"))
            ok = c.getresponse().status == 200
            c.close()
            return ok
        except (OSError, http.client.HTTPException):
            return False

    def managed(self, name):
        return name in self.mods

    def begin(self, name):
        if name in self.state:
            self.state[name]["inflight"] += 1
            self.state[name]["last"] = self.clock()

    def end(self, name):
        if name in self.state:
            self.state[name]["inflight"] = max(0, self.state[name]["inflight"] - 1)
            self.state[name]["last"] = self.clock()

    def ensure(self, name):
        """Make sure the module is answering. Returns (ok, reason) where reason is 'starting', 'failed' or ''."""
        m, st = self.mods[name], self.state[name]
        if self.healthy(m):
            return True, ""
        with st["lock"]:                       # one request starts it; concurrent ones wait on the same start
            if self.healthy(m):
                return True, ""
            if not (st["proc"] and st["proc"].poll() is None):
                err = self._launch(name)
                if err:
                    st["error"] = err
                    return False, "failed"
            deadline = time.time() + float(m.get("wake_timeout", 40))
            while time.time() < deadline:
                if self.healthy(m):
                    st["error"] = ""
                    return True, ""
                if st["proc"] and st["proc"].poll() is not None:
                    st["error"] = f"exited with code {st['proc'].returncode}; see logs/{name}.log"
                    return False, "failed"
                time.sleep(0.25)
        return False, "starting"

    def _launch(self, name):
        m, st = self.mods[name], self.state[name]
        cwd = resolve_cwd(m["start"]["cwd"])
        if not cwd:
            return f"module folder not found: {m['start']['cwd']}"
        cmd = [sys.executable if c == "{python}" else _fill(c, m) for c in m["start"]["cmd"]]
        os.makedirs(LOG_DIR, exist_ok=True)
        env = dict(os.environ, NEXXUS_MODULE_NAME=name, NEXXUS_MODULE_PORT=str(m.get("port", "")),
                   **({"NEXXUS_MODULE_WEBHOOK_PORT": str(m["webhook_port"])} if m.get("webhook_port") else {}),
                   **{k: _fill(v, m) for k, v in m["start"].get("env", {}).items()})
        flags = (0x08000000 | 0x00000200) if os.name == "nt" else 0   # no console window, own process group
        try:
            st["proc"] = subprocess.Popen(cmd, cwd=cwd, env=env, stdin=subprocess.DEVNULL, stdout=open(os.path.join(LOG_DIR, f"{name}.log"), "ab"),
                                          stderr=subprocess.STDOUT, creationflags=flags)
        except OSError as exc:
            return f"could not start: {exc}"
        st["owned"] = True
        if self.on_event:
            self.on_event("module_start", module=name, port=m.get("port"))
        return ""

    def stop(self, name):
        st = self.state.get(name)
        if not st or not st["owned"] or not st["proc"] or st["proc"].poll() is not None:
            if st:
                st["owned"] = False
            return False
        p = st["proc"]
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(p.pid), "/T", "/F"], capture_output=True)
        else:
            p.terminate()
        try:
            p.wait(timeout=10)
        except subprocess.TimeoutExpired:
            p.kill()
        st["owned"] = False
        if self.on_event:
            self.on_event("module_stop", module=name)
        return True

    def reap(self):
        """Rest every module the gateway started that has been idle past its limit and has nothing in flight."""
        rested = []
        for name, m in self.mods.items():
            st, idle = self.state[name], float(m.get("idle_minutes") or 0)
            if idle > 0 and st["owned"] and st["inflight"] == 0 and self.clock() - st["last"] > idle * 60:
                if self.stop(name):
                    rested.append(name)
        return rested

    def keepalive(self):
        """Start every module marked keep_running, and bring back any that has died. Backs off if one keeps crashing."""
        revived = []
        for name, m in self.mods.items():
            st = self.state[name]
            if not m.get("keep_running") or self.clock() < st.get("next_try", 0) or st.get("reviving") or self.healthy(m):
                st["fails"] = 0 if self.healthy(m) else st.get("fails", 0)
                continue

            def revive(n=name, s=st):
                s["reviving"] = True
                try:
                    ok, _ = self.ensure(n)
                    s["fails"] = 0 if ok else s.get("fails", 0) + 1
                    if s["fails"] >= 5:                       # crash loop: wait 5 minutes before trying again
                        s["next_try"] = self.clock() + 300
                        s["fails"] = 0
                finally:
                    s["reviving"] = False
            threading.Thread(target=revive, daemon=True).start()
            revived.append(name)
        return revived

    def shutdown(self):
        """Gateway exit: only stop modules that were set to rest; keep_running modules are left running."""
        for name, m in self.mods.items():
            if not m.get("keep_running"):
                self.stop(name)

    def status(self):
        out = []
        for name, m in self.cfg["modules"].items():
            row = {"name": name, "type": m.get("type", "app"), "hostnames": m["hostnames"], "idle_minutes": m.get("idle_minutes"), "keep_running": bool(m.get("keep_running")),
                   "note": m.get("note", ""), "talks_to_bridge": bool(m.get("talks_to_bridge")), "nexxus": bool(m.get("_nexxus"))}
            if row["type"] == "static":
                row["state"] = "always on"
            elif name in self.mods:
                st = self.state[name]
                up = self.healthy(m)
                row["state"] = ("running" if up else "waking" if st["proc"] and st["proc"].poll() is None else "resting")
                row["started_by_gateway"] = st["owned"]
                row["idle_for_s"] = int(self.clock() - st["last"]) if st["last"] else None
                row["error"] = st["error"]
            else:
                row["state"] = "running" if self.healthy(m) else "stopped (not managed by the gateway)"
            out.append(row)
        return out


class Registry:
    """The live routing table. With a ui_dir it re-scans for dropped-in or removed modules; without one it is just the given config."""

    def __init__(self, base_cfg, ui_dir=None, publish_path=None, sup=None, clock=time.time, min_interval=2.0, auto=None, buslog=None):
        self.base, self.ui_dir, self.publish_path, self.clock, self.min_interval = base_cfg, ui_dir, publish_path, clock, min_interval
        self.auto, self.buslog = auto, buslog or BusLog(None)
        self.bridge, self.bridge_hosts = None, set()
        self.problems, self.last = [], 0.0
        self.cfg, self.routes = base_cfg, {}
        self.sup = sup or Supervisor(base_cfg, clock=clock)
        self.sup.on_event = self.buslog.event
        self.lock = threading.Lock()
        self.reload(force=True)

    def reload(self, force=False):
        if not self.ui_dir and not force:
            return False
        if not force and self.clock() - self.last < self.min_interval:
            return False
        with self.lock:
            self.last = self.clock()
            cfg, problems = discover(self.base, self.ui_dir, self.auto) if self.ui_dir else (self.base, [])
            if self.publish_path and self.ui_dir:
                problems += publish_for_nexxus(cfg, self.publish_path, cfg["gateway"].get("port", 8080))
            changed = json.dumps(cfg, sort_keys=True, default=str) != json.dumps(self.cfg, sort_keys=True, default=str) or not self.routes
            self.problems = problems
            if changed:
                self.sup.update(cfg)
                self.cfg = cfg
                self.routes = {h.lower(): (n, m) for n, m in cfg["modules"].items() for h in m["hostnames"]}
                self.bridge = cfg.get("bridge")
                self.bridge_hosts = {str(h).lower() for h in (self.bridge or {}).get("hostnames", [])}
                self.buslog.event("routes_changed", modules=",".join(cfg["modules"]))
            return changed


