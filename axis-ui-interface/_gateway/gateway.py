def make_handler(reg):
    class Handler(BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.0"
        server_version = "AxisGateway/2.0"
        registry = reg

        def log_message(self, *a):
            pass

        def send_response(self, code, message=None):
            self._status = code
            super().send_response(code, message)

        def _send(self, code, data, ctype="text/plain; charset=utf-8", extra=None):
            data = data if isinstance(data, bytes) else data.encode()
            self._out = getattr(self, "_out", 0) + len(data)
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(data)))
            for k, v in (extra or {}).items():
                self.send_header(k, v)
            self.end_headers()
            if self.command != "HEAD":
                self.wfile.write(data)

        def _text(self, code, msg):
            self._send(code, msg)

        def _launcher(self, path):
            reg.reload()
            sup, port = reg.sup, self.server.server_address[1]
            if self.command in ("GET", "HEAD") and path == "/":
                return self._send(200, launcher_html(sup.status(), port, reg.problems), "text/html; charset=utf-8", {"Cache-Control": "no-store"})
            if self.command in ("GET", "HEAD") and path == "/_status":
                up = False
                if reg.bridge:
                    try:
                        import socket
                        socket.create_connection(("127.0.0.1", int(reg.bridge["port"])), timeout=0.8).close(); up = True
                    except OSError:
                        up = False
                return self._send(200, json.dumps({"modules": sup.status(), "problems": reg.problems,
                                                   "bridge": ({"hostnames": reg.bridge.get("hostnames", []), "up": up} if reg.bridge else None)}),
                                  "application/json", {"Cache-Control": "no-store"})
            parts = path.strip("/").split("/")
            if self.command == "POST" and len(parts) == 2 and parts[0] in ("_start", "_stop") and parts[1] in sup.mods:
                origin = self.headers.get("Origin")
                if origin and urllib.parse.urlparse(origin).netloc != (self.headers.get("Host") or ""):
                    return self._text(403, "Cross-site request refused")
                if parts[0] == "_start":
                    threading.Thread(target=sup.ensure, args=(parts[1],), daemon=True).start()
                    return self._send(202, '{"ok": true}', "application/json")
                return self._send(200, json.dumps({"ok": sup.stop(parts[1])}), "application/json")
            return self._text(404, "Not found")

        def _handle(self):
            """Every request is recorded in the private bus log (who/what/status/size/time - never contents), whatever happens."""
            t0, self._status, self._out, self._mod, self._outside = time.time(), 0, 0, "-", False
            try:
                self._dispatch()
            finally:
                try:
                    reg.buslog.request(self._mod, self.headers.get("Host") or "", self.command, self.path, self._status,
                                       int(self.headers.get("Content-Length") or 0), self._out, int((time.time() - t0) * 1000), self._outside)
                except Exception:
                    pass

        def _bridge(self, path):
            """nexxus.localhost -> the NEXXUS bridge (port 8000). ONLY for requests made on this computer by a program here:
            anything that arrived through a tunnel, a proxy or from another machine gets the same plain 404 as an unknown host,
            and a cross-site POST is refused. This route can never be switched off its local-only rule."""
            self._mod = "nexxus"
            self._outside = is_outside(self.headers, self.client_address[0])
            if self._outside:
                reg.buslog.event("bridge_refused_outside", client=self.client_address[0])
                return self._text(404, "Unknown host")
            if self.command in ("POST", "PUT", "PATCH", "DELETE"):
                origin = self.headers.get("Origin")
                if origin and urllib.parse.urlparse(origin).netloc != (self.headers.get("Host") or ""):
                    return self._text(403, "Cross-site request refused")
            self._proxy("nexxus", int(reg.bridge["port"]), {"proxy_timeout": reg.bridge.get("proxy_timeout", 300)})

        def _dispatch(self):
            raw_host = (self.headers.get("Host") or "").lower()
            host = raw_host.split(":")[0] if not raw_host.startswith("[") else raw_host.split("]")[0] + "]"
            path = urllib.parse.urlparse(self.path).path
            if host in LAUNCHER_HOSTS:
                self._mod = "(launcher)"
                return self._launcher(path)
            if host in reg.bridge_hosts:
                return self._bridge(path)
            route = reg.routes.get(host)
            if not route and reg.reload():                # a module may have just been dropped in
                route = reg.routes.get(host)
            if not route:
                return self._text(404, "Unknown host")
            name, module = route
            self._mod = name
            sup = reg.sup
            if module.get("type") == "static":
                return self._static(module, path)
            if any(path.startswith(pp) for pp in module.get("private_paths", [])):
                # Machine-only paths (e.g. NEXXUS's signed window): only requests made on this computer that did not
                # come through a proxy or tunnel. Anything arriving from outside gets a plain 404.
                outside = any(self.headers.get(h) for h in STRIPPED_FROM_CLIENT) or self.client_address[0] not in ("127.0.0.1", "::1")
                self._outside = outside
                if outside:
                    return self._text(404, "Not found")
            port = module["port"]
            if module.get("webhook_port") and any(path.startswith(p) if p.endswith("/") else path == p for p in module.get("webhook_paths", [])):
                port = module["webhook_port"]
            if sup.managed(name):
                ok, why = sup.ensure(name)
                if not ok:
                    if why == "starting":
                        return self._send(503, WAKING_PAGE.format(name=html.escape(name)), "text/html; charset=utf-8", {"Retry-After": "3"})
                    return self._text(502, f"The '{name}' module could not be started: {sup.state[name]['error']}")
            sup.begin(name)
            try:
                self._proxy(name, port, module)
            finally:
                sup.end(name)

        def _proxy(self, name, port, module):
            n = int(self.headers.get("Content-Length") or 0)
            if n > MAX_BODY:
                return self._text(413, "Request too large")
            body = self.rfile.read(n) if n else None
            headers = {k: v for k, v in self.headers.items() if k.lower() not in HOP_BY_HOP | STRIPPED_FROM_CLIENT}
            headers["X-Forwarded-For"] = self.client_address[0]  # set by us, never trusted from the client
            headers["X-Forwarded-Proto"] = "http"  # this hop is plain HTTP; a TLS edge in front of the gateway sets its own
            conn = http.client.HTTPConnection("127.0.0.1", port, timeout=_proxy_timeout(module))  # always loopback, always the module's own port
            try:
                conn.request(self.command, self.path, body=body, headers=headers)
                resp = conn.getresponse()
                data = resp.read()
            except (OSError, http.client.HTTPException):
                return self._text(502, f"The '{name}' module is not responding.")
            finally:
                conn.close()
            self.send_response(resp.status)
            for k, v in resp.getheaders():  # getheaders keeps repeated headers such as several Set-Cookie
                if k.lower() not in HOP_BY_HOP:
                    self.send_header(k, v)
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self._out = getattr(self, "_out", 0) + len(data)
            if self.command != "HEAD":
                self.wfile.write(data)

        def _static(self, module, path):
            root = os.path.realpath(module["root"] if os.path.isabs(module["root"]) else os.path.join(HERE, module["root"]))
            rel = posixpath.normpath(urllib.parse.unquote(path)).lstrip("/")
            rel = rel or module.get("index", "index.html")
            if self.command not in ("GET", "HEAD"):
                return self._text(405, "Method not allowed")
            target = os.path.realpath(os.path.join(root, rel))
            inside = target == root or target.startswith(root + os.sep)
            rel_ok = inside and os.path.relpath(target, root).replace(os.sep, "/")
            ext_ok = os.path.splitext(target)[1].lower() in (".html", ".css", ".js", ".png", ".jpg", ".jpeg", ".svg", ".gif", ".webp", ".ico", ".json", ".woff2")
            listed = bool(rel_ok) and (rel_ok in module.get("files", []) or any(rel_ok.startswith(p) for p in module.get("prefixes", [])))  # allow-list only
            if not (inside and listed and ext_ok and os.path.isfile(target)):
                return self._text(404, "Not found")
            with open(target, "rb") as f:
                data = f.read()
            self._send(200, data, mimetypes.guess_type(target)[0] or "application/octet-stream", {"X-Content-Type-Options": "nosniff"})

        do_GET = do_POST = do_PUT = do_PATCH = do_DELETE = do_HEAD = do_OPTIONS = _handle

    return Handler


def make_server(cfg, sup=None, registry=None):
    reg = registry or Registry(cfg, sup=sup)
    gw = reg.cfg.get("gateway", {})
    srv = ThreadingHTTPServer((gw.get("host", "127.0.0.1"), int(gw.get("port", 8080))), make_handler(reg))
    srv.registry, srv.supervisor = reg, reg.sup
    return srv


def main():
    base = load_config()
    publish = os.path.normpath(os.path.join(UI_DIR, base["publish_nexxus"])) if base.get("publish_nexxus") else None
    reg = Registry(base, ui_dir=UI_DIR, publish_path=publish, auto=AutoPorts(AUTO_PORTS_PATH), buslog=BusLog(BUS_LOG_PATH))
    reg.buslog.event("gateway_start", port=base.get("gateway", {}).get("port"))
    problems = validate(dict(reg.cfg, modules={k: v for k, v in reg.cfg["modules"].items() if k in base.get("modules", {})}))
    if problems:
        print("ports.json problems:\n - " + "\n - ".join(problems))
        sys.exit(1)
    if "--check" in sys.argv:
        for n, m in reg.cfg["modules"].items():
            print(f"module {n}: {','.join(m['hostnames'])}  ({m.get('type', 'app')}{', NEXXUS window' if m.get('_nexxus') else ''})")
        for p in reg.problems:
            print("PROBLEM:", p)
        print("discovery OK" if not reg.problems else "discovery finished with problems (the rest still work)")
        return
    srv = make_server(base, registry=reg)
    gw = reg.cfg["gateway"]

    def watchdog():
        while True:
            reg.reload()
            for name in reg.sup.keepalive():
                print(f"[GATEWAY] starting/restarting {name}", flush=True)
                reg.buslog.event("module_revive", module=name)
            for name in reg.sup.reap():     # only modules explicitly given idle_minutes
                print(f"[GATEWAY] {name} rested after sitting idle", flush=True)
            time.sleep(10)
    threading.Thread(target=watchdog, daemon=True).start()
    print(f"[GATEWAY] http://{gw.get('host', '127.0.0.1')}:{gw['port']}/  modules: " + (", ".join(reg.cfg["modules"]) or "(none yet)"), flush=True)
    try:
        srv.serve_forever()
    finally:
        reg.sup.shutdown()


if __name__ == "__main__":
    main()
