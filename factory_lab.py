"""factory_lab.py - a live demo and a heavy-load stress test for every dashboard type, with telemetry the dashboard can show.

Honest scope. A DEMO builds a real instance of the type from a configuration the lab generates (labelled demo: true, named "Lab demo ..."), in the same engine the owner uses, and checks it.
A STRESS run drives the real engine at volume (many products, thousands of physics bodies, many bots and chained runs, real video renders) while a sampler records the process's CPU and memory.
The load is generated by the lab and is a test of the machinery, not data about anything; nothing a stress run creates is kept as the owner's data (it uses a temporary hub and is removed).
Two runs of the same type at once are refused (the lab is one-at-a-time per type), and every report says what was measured and what was not.
Every result is appended to telemetry.jsonl and returned.
"""
import json
import os
import re
import shutil
import tempfile
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import factory_env
import factory_hub
import factory_types
import micro_company

try:
    import psutil
except ImportError:                                   # telemetry then says the sampler is unavailable
    psutil = None


class LabError(Exception):
    pass


class _Sampler:
    """Samples this process's CPU % and resident memory while a test runs."""

    def __init__(self, every=0.1):
        self.every, self.cpu, self.rss, self._stop, self._t = every, [], [], threading.Event(), None
        self.proc = psutil.Process(os.getpid()) if psutil else None

    def __enter__(self):
        if self.proc:
            self.proc.cpu_percent(None)
            self._t = threading.Thread(target=self._run, daemon=True)
            self._t.start()
        return self

    def _run(self):
        while not self._stop.wait(self.every):
            try:
                self.cpu.append(self.proc.cpu_percent(None))
                self.rss.append(self.proc.memory_info().rss)
            except psutil.Error:
                break

    def __exit__(self, *a):
        self._stop.set()
        if self._t:
            self._t.join(2)

    def summary(self):
        if not self.proc:
            return {"sampler": "unavailable (psutil is not installed)"}
        if not self.rss:
            return {"sampler": "no samples (the run was shorter than one sample interval)"}
        return {"cpu_peak_pct": round(max(self.cpu), 1), "cpu_mean_pct": round(sum(self.cpu) / len(self.cpu), 1), "rss_peak_mb": round(max(self.rss) / 1048576, 1),
                "rss_growth_mb": round((self.rss[-1] - self.rss[0]) / 1048576, 1), "samples": len(self.rss), "threads": self.proc.num_threads()}


def _png(path, rgb):
    from PIL import Image
    Image.new("RGB", (64, 64), rgb).save(path, "PNG")


class Lab:
    def __init__(self, root, services=None, now=time.time):
        self.root, self.services, self.now = Path(root), services or {}, now
        self.root.mkdir(parents=True, exist_ok=True)
        self._busy, self._lock = set(), threading.Lock()
        self.log = self.root / "telemetry.jsonl"

    # ---- plumbing ----
    def _record(self, rec):
        rec = dict(rec, at=round(self.now(), 3))
        with self._lock, open(self.log, "a", encoding="utf-8") as f:
            f.write(json.dumps(rec, default=str) + "\n")
        return rec

    def telemetry(self, limit=50):
        try:
            lines = self.log.read_text(encoding="utf-8").splitlines()[-int(limit):]
        except OSError:
            return []
        out = []
        for l in lines:
            try:
                out.append(json.loads(l))
            except ValueError:
                continue
        return out

    def _claim(self, key):
        with self._lock:
            if key in self._busy:
                raise LabError("a lab run for %s is already in progress" % key)
            self._busy.add(key)

    def _release(self, key):
        with self._lock:
            self._busy.discard(key)

    def _tmp_hub(self, services=None, resolver=None):
        d = Path(tempfile.mkdtemp(prefix="nx-lab-", dir=str(self.root)))
        return d, factory_hub.Hub(d, services or self.services, resolver)

    # ---- generated configurations (demo / load; labelled, never the owner's data) ----
    @staticmethod
    def demo_config(type_key, scale=1):
        if type_key == "platform_factory":
            return {"brand": "Lab demo", "tagline": "Generated by the NEXXUS lab", "kind": "storefront", "accent": "#38bdf8", "about": "A lab-generated storefront used to test the platform generator.",
                    "products": [{"name": "Lab item %d" % (i + 1), "price": 5 + i % 40, "currency": "usd", "description": "Lab-generated product %d." % (i + 1), "asset": "lab-asset"} for i in range(max(1, int(3 * scale)))]}
        if type_key == "spatial_environment":
            n = max(1, int(60 * scale))
            objs = [{"shape": "box", "size": [6, 1, 6], "position": [0, 0.5, 0], "color": "#334155"}]
            objs += [{"shape": ("sphere", "box", "cylinder")[i % 3], "size": ([0.8], [0.8, 0.8, 0.8], [0.8, 1])[i % 3], "position": [(i % 17) - 8, 3 + (i // 17) * 0.9, ((i // 3) % 15) - 7], "color": "#f97316", "dynamic": True, "mass": 1} for i in range(n)]
            return {"title": "Lab demo", "ground": 40, "gravity": 9.81, "objects": objs, "lights": [{"type": "hemispheric", "intensity": 0.8}, {"type": "directional", "intensity": 0.8, "position": [-10, 20, -10]}],
                    "player": {"start": [0, 1.7, -16], "speed": 5, "height": 1.7}}
        if type_key == "micro_company":
            bots = [{"name": "Watch", "task": "health_check", "every_s": 5, "then": "Log"}, {"name": "Log", "task": "report"}]
            return {"company": "Lab demo", "purpose": "Lab-generated company used to test the scheduler and hand-off chain.", "bots": bots}
        if type_key == "publishing_pipeline":
            return {"topic": "lab test", "brief": "This card is rendered by the NEXXUS lab.\nThe video is a real mp4 file.\nIt is queued for review and never uploaded by the lab.", "title": "Lab demo video", "tags": ["lab"]}
        raise LabError("no demo exists for %r: only the built-in types have one (a custom type is built with the engine you gave it)" % type_key)

    def _resolver(self, d):
        _png(d / "lab.png", (30, 120, 200))
        data = (d / "lab.png").read_bytes()
        return lambda cid: [("lab.png", data)] if cid == "lab-asset" else None

    # ---- demo ----
    def demo(self, hub, type_key):
        """Build a real demo instance inside the OWNER's hub (labelled demo: true so it can be told apart and deleted), and check it."""
        if type_key not in factory_types.BUILTIN:
            raise LabError("no demo exists for %r" % type_key)
        self._claim("demo:" + type_key)
        try:
            cfg = self.demo_config(type_key)
            d = Path(tempfile.mkdtemp(prefix="nx-lab-asset-", dir=str(self.root)))
            if type_key == "platform_factory" and hub.resolver is None:
                hub.resolver = self._resolver(d)
            rec = hub.create(type_key, "Lab demo (%s)" % factory_types.BUILTIN[type_key]["title"], cfg, demo=True)
            build = hub.build(type_key, rec["id"])
            extra = {}
            if type_key in ("micro_company", "publishing_pipeline"):
                extra["note"] = "built, not started: deploy it to run it" if type_key == "micro_company" else "built, not started: running it renders a real mp4 and stages it for review"
            return self._record({"kind": "demo", "type": type_key, "instance": rec["id"], "ok": build["ok"], "build_ms": build["ms"], "problems": build["problems"], **extra})
        finally:
            self._release("demo:" + type_key)

    # ---- stress ----
    def stress(self, type_key, level="heavy"):
        if level not in ("light", "heavy"):
            raise LabError("level must be light or heavy")
        fn = {"platform_factory": self._stress_platform, "spatial_environment": self._stress_env, "micro_company": self._stress_company, "publishing_pipeline": self._stress_pipeline}.get(type_key)
        if fn is None:
            raise LabError("stress tests exist for the built-in types only")
        self._claim("stress:" + type_key)
        d, hub = None, None
        t0 = time.perf_counter()
        try:
            with _Sampler() as s:
                res = fn(level)
            res.update(kind="stress", type=type_key, level=level, seconds=round(time.perf_counter() - t0, 2), **s.summary())
            return self._record(res)
        finally:
            self._release("stress:" + type_key)

    def _stress_platform(self, level):
        n_inst, n_prod = (4, 20) if level == "light" else (16, 100)
        d, hub = self._tmp_hub()
        try:
            hub.resolver = self._resolver(d)
            cfg = self.demo_config("platform_factory", scale=n_prod / 3)
            recs = [hub.create("platform_factory", "Lab load %d" % i, dict(cfg, brand="Lab load %d" % i)) for i in range(n_inst)]
            with ThreadPoolExecutor(max_workers=8) as ex:                             # concurrent builds of different instances
                builds = list(ex.map(lambda r: hub.build("platform_factory", r["id"]), recs))
            ms = sorted(b["ms"] for b in builds)
            def own_brand_only(i, r):
                page = (hub.factory.workdir("platform_factory", r["id"]) / "site" / "index.html").read_text(encoding="utf-8")
                return set(re.findall(r"Lab load (\d+)", page)) == {str(i)}               # this instance's page names itself and no sibling
            isolated = all(own_brand_only(i, r) for i, r in enumerate(recs))
            bad = [r["id"] for r, b in zip(recs, builds) if not b["ok"]]
            pages = sum(len(b["info"]["pages"]) for b in builds)
            return {"ok": not bad and isolated, "instances": n_inst, "products_each": n_prod, "pages_built": pages, "build_ms_p50": ms[len(ms) // 2], "build_ms_max": ms[-1], "failed": bad,
                    "isolated_outputs": isolated, "measured": "concurrent site builds incl. self-check; not measured: browser rendering time"}
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def _stress_env(self, level):
        bodies, steps = (500, 300) if level == "light" else (3000, 600)
        cfg = self.demo_config("spatial_environment", scale=bodies / 60)
        cfg["ground"] = 120
        for o in cfg["objects"][1:]:
            o["position"][0] *= 3; o["position"][2] *= 3
        r = factory_env.simulate(cfg, steps)
        ok = r["faults"] == 0 and r["out_of_bounds"] == 0 and r["step_ms"] < 1000 / 20          # the physics must keep 20 steps/s even at this load
        return {"ok": ok, "bodies": r["bodies"], "steps": r["steps"], "step_ms": round(r["step_ms"], 3), "peak_contacts": r["peak_contacts"], "faults": r["faults"], "out_of_bounds": r["out_of_bounds"],
                "node_heap_mb": round(r["heap_mb"], 1), "measured": "headless physics under Node (same physics.js the page loads); not measured: GPU rendering frame rate, which only a browser on this screen can report"}

    def _stress_company(self, level):
        n_bots, rounds = (6, 50) if level == "light" else (20, 400)
        counts = {"n": 0}
        lk = threading.Lock()

        def health():
            with lk:
                counts["n"] += 1
            return {"ok": True}
        d = Path(tempfile.mkdtemp(prefix="nx-lab-co-", dir=str(self.root)))
        try:
            bots = [{"name": "B%d" % i, "task": "health_check", "then": ("B%d" % (i + 1)) if i % 4 != 3 and i + 1 < n_bots else None} for i in range(n_bots)]
            co = micro_company.MicroCompany(d, {"company": "Lab load", "bots": bots}, {"health": health})
            co._hist = {}
            starts = [b["name"] for b in bots]
            t0 = time.perf_counter()

            def work(k):
                out = []
                for _ in range(rounds // 4):
                    out += co.run_bot(starts[k % len(starts)])
                return out
            with ThreadPoolExecutor(max_workers=4) as ex:
                runs = [r for part in ex.map(work, range(4)) for r in part]
            dt = time.perf_counter() - t0
            led_ok, led_n = co.verify_ledger()
            capped = sum(1 for r in runs if r.get("error") == "hourly run cap reached")
            failed = [r for r in runs if not r["ok"] and r.get("error") != "hourly run cap reached"]
            return {"ok": bool(led_ok and not failed), "bots": n_bots, "runs": len(runs), "runs_per_s": round(len(runs) / max(dt, 1e-6)), "failed": len(failed), "cap_refusals": capped, "ledger_intact": led_ok,
                    "ledger_entries": led_n, "handler_calls": counts["n"], "measured": "scheduler, hand-off chain, caps and ledger under 4 concurrent threads using the real health handler; handlers that call other systems are covered by the pipeline run"}
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def _stress_pipeline(self, level):
        n = 2 if level == "light" else 5
        import video_maker
        d = Path(tempfile.mkdtemp(prefix="nx-lab-pipe-", dir=str(self.root)))
        try:
            outs, t0 = [], time.perf_counter()
            for i in range(n):
                r = video_maker.make(d / ("v%d.mp4" % i), "Lab video %d" % (i + 1), ["Line one of video %d." % (i + 1), "Line two of video %d." % (i + 1), "Line three, which is longer so that the card has to wrap onto a second row of text on screen."], 2)
                v = video_maker.verify(r["path"], r["frames"])
                outs.append({"bytes": r["bytes"], "frames": r["frames"], "decodes": v["ok"], "render_s": round(time.perf_counter() - t0, 2)})
                t0 = time.perf_counter()
            ok = all(o["decodes"] for o in outs)
            return {"ok": ok, "videos": n, "all_decode": ok, "total_bytes": sum(o["bytes"] for o in outs), "render_s_each": [o["render_s"] for o in outs],
                    "measured": "real mp4 renders and a decode of each file; the queue is exercised by test_publish_queue.py, and nothing is uploaded by the lab"}
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def isolation(self, hub):
        """Prove types do not bleed: each instance's folder holds only its own type's files, and no two instances share a folder."""
        seen, problems = {}, []
        for rec in hub.factory.list():
            w = str(hub.factory.workdir(rec["type"], rec["id"]))
            if w in seen:
                problems.append("%s and %s share a folder" % (rec["id"], seen[w]))
            seen[w] = rec["id"]
            if rec["type"] != Path(w).parent.name:
                problems.append("%s is stored under the wrong type" % rec["id"])
        return self._record({"kind": "isolation", "ok": not problems, "instances": len(seen), "problems": problems})
